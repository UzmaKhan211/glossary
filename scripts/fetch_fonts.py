#!/usr/bin/env python3
"""
Download the free substitute fonts used by templates/style.css (see
scripts/grade_fonts.py for the grade->font mapping) and write
templates/fonts.css. Run this once after cloning -- templates/fonts/*.woff2
and templates/fonts.css are gitignored/regenerable, not checked in, since
they're just a `curl` away and bulky to carry around.

Only the latin-subset, exact weights actually used by the templates are
fetched (see README.md for which family/weight maps to which grade).
"""
import os
import re
import urllib.request
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = REPO_ROOT / "templates" / "fonts"
FONTS_CSS = REPO_ROOT / "templates" / "fonts.css"

UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/124.0 Safari/537.36")

# (Google Fonts family name, weight) actually referenced by style.css / grade_fonts.py
WANTED = [
    ("Poppins", 700),
    ("Source Sans 3", 400),
    ("Baloo 2", 800),
    ("Nunito", 400),
]

FACE_RE = re.compile(r"@font-face\s*\{([^}]*)\}")
PROP_RE = re.compile(r"([\w-]+):\s*([^;]+);")


def fetch_family_css(family, weight):
    url = f"https://fonts.googleapis.com/css2?family={family.replace(' ', '+')}:wght@{weight}&display=swap"
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    return urllib.request.urlopen(req, timeout=20).read().decode()


def main():
    FONT_DIR.mkdir(parents=True, exist_ok=True)
    face_blocks = []

    for family, weight in WANTED:
        css = fetch_family_css(family, weight)
        for block in FACE_RE.findall(css):
            props = dict(PROP_RE.findall(block))
            if "U+0000-00FF" not in props.get("unicode-range", "").upper():
                continue  # only the plain latin subset
            style = props.get("font-style", "normal").strip()
            src_m = re.search(r"url\((https://[^)]+)\)", props["src"])
            url = src_m.group(1)
            ext = os.path.splitext(url)[1]
            fname = f"{family.replace(' ', '')}-{weight}{ext}"
            dest = FONT_DIR / fname
            urllib.request.urlretrieve(url, dest)
            print(f"{family} {weight} -> {fname} ({dest.stat().st_size} bytes)")
            face_blocks.append(f"""@font-face {{
  font-family: '{family}';
  font-style: {style};
  font-weight: {weight};
  font-display: swap;
  src: url('fonts/{fname}') format('woff2');
}}""")
            break  # first matching latin block is enough per (family, weight)

    FONTS_CSS.write_text(
        "/* Generated by scripts/fetch_fonts.py -- do not hand-edit. */\n\n"
        + "\n\n".join(face_blocks) + "\n"
    )
    print(f"Wrote {FONTS_CSS} with {len(face_blocks)} @font-face rules")


if __name__ == "__main__":
    main()
