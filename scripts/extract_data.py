#!/usr/bin/env python3
"""
Extract Word Wall vocabulary cards from the NA K-5 Glossary Updates and Feedback
spreadsheet and produce a clean data/vocab.json for the card generator.

The source spreadsheet is an editorial proofing sheet, not a clean production
table: each grade (K,1,2,3,4,5) has a 4-column block (Current, Image, Feedback,
New Entry), definitions are duplicated across two revisions, and "go-by" images
are floating drawings anchored to a cell rather than cell values. See
data/qa_report.md (generated by this script) for every judgment call made below,
row by row, so it can be spot-checked before anything ships.

Rules used (confirmed by inspecting every image anchor + surrounding text in the
sheet -- see conversation / audit notes):

  Definition text: prefer "New Entry" (the proofread revision), fall back to
  "Current" when New Entry is blank. Both are cleaned of stray reviewer
  markup (leading "word: " restatement, "**...**"/"***...***" editorial asides).

  Image: a row can have a go-by image anchored in any of the 4 columns for a
  grade, not just the "Image" column, because editors sometimes paste a
  replacement image into "Feedback" (staging a swap) or -- for image-only
  entries (K, and some Grade 1/2 shape & comparative words) -- directly into
  "Current"/"New Entry" since those grades don't need text. Priority, newest
  first: Feedback > Image > New Entry > Current.

  Word: derived from column A (handles "a foot/ feet" -> "foot" style
  variants). Column D ("Overall Feedback") is mostly free-form editorial notes
  ("add in 5th", "remove from 2nd") and is NOT a reliable word source, except
  when it literally reads "entry: X" / "entry word: X", which means "use X".
"""
import base64
import json
import re
import sys
import zipfile
from collections import defaultdict
from pathlib import Path
from xml.etree import ElementTree as ET

import openpyxl

REPO_ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = REPO_ROOT / "data"
IMAGES_DIR = REPO_ROOT / "assets" / "images"

GRADE_COLS = {
    "K": ("F", "G", "H", "I"),
    "1": ("J", "K", "L", "M"),
    "2": ("N", "O", "P", "Q"),
    "3": ("R", "S", "T", "U"),
    "4": ("V", "W", "X", "Y"),
    "5": ("Z", "AA", "AB", "AC"),
}
ROLE_NAMES = ("current", "image", "feedback", "new_entry")

# Image priority, newest/most-authoritative first.
IMAGE_ROLE_PRIORITY = ("feedback", "image", "new_entry", "current")

# Confirmed one-off word corrections found during data audit (see qa_report.md).
# D column said something like "remove parentheses around sides" (an instruction,
# not a literal replacement word) -- these are hand-fixed rather than guessed at.
MANUAL_WORD_OVERRIDES = {
    17: "adjacent",       # D: "remove parentheses around sides" -> "adjacent (sides)" -> "adjacent"
    106: "hundredths",    # A: "hundreths** " (typo + stray markup) -> corrected spelling
}

ENTRY_PREFIX_RE = re.compile(r"^(?:entry word|entry)\s*:\s*(.+)$", re.IGNORECASE)
LEADING_ARTICLE_RE = re.compile(r"^(a|an)\s+", re.IGNORECASE)
TRAILING_NUMERIC_PAREN_RE = re.compile(r"\s*\(\d[\d/]*\)\s*$")
LEADING_ASTERISK_CALLOUT_RE = re.compile(r"^\*{2,}[^*]*\*{2,}\s*")
LEADING_WORD_COLON_RE = re.compile(r"^([A-Za-z][A-Za-z '/-]{0,40}):\s*(.*)$", re.DOTALL)


def col_letter(col0: int) -> str:
    """0-indexed column number -> Excel column letter."""
    col1 = col0 + 1
    letters = ""
    while col1 > 0:
        col1, rem = divmod(col1 - 1, 26)
        letters = chr(65 + rem) + letters
    return letters


def clean_definition(raw, word):
    if not raw:
        return ""
    text = str(raw).strip()
    text = LEADING_ASTERISK_CALLOUT_RE.sub("", text).strip()
    # Trailing editorial notes: real content never follows a run of 2+ asterisks.
    text = re.split(r"\*{2,}", text)[0].strip()
    m = LEADING_WORD_COLON_RE.match(text)
    if m:
        text = m.group(2).strip()
    text = re.sub(r"\s*\n\s*", " ", text)
    text = re.sub(r"\s{2,}", " ", text).strip()
    # House style (matches the prototype: "a type of rectangle...", "a blank
    # number line...") reads as a sentence fragment completing the word, not
    # a capitalized sentence. Lowercase the first letter, but leave true
    # acronyms alone (a capital immediately followed by another capital).
    if len(text) >= 2 and text[0].isupper() and not text[1].isupper():
        text = text[0].lower() + text[1:]
    # House style also drops the trailing period (prototype: "...4 square
    # corners" / "...problems and strategies", no full stop) since these
    # read as fragments, not standalone sentences.
    if text.endswith(".") and not text.endswith(".."):
        text = text[:-1].rstrip()
    return text


def clean_word(a_raw, d_raw, row):
    if row in MANUAL_WORD_OVERRIDES:
        return MANUAL_WORD_OVERRIDES[row]

    d = str(d_raw).strip() if d_raw else ""
    m = ENTRY_PREFIX_RE.match(d)
    if m:
        return m.group(1).strip()

    s = str(a_raw).split("\n")[0]
    s = s.split("/")[0]
    s = LEADING_ARTICLE_RE.sub("", s)
    s = TRAILING_NUMERIC_PAREN_RE.sub("", s)
    return s.strip()


def slugify(word):
    s = re.sub(r"[^a-z0-9]+", "-", word.lower()).strip("-")
    return s or "word"


def parse_drawing_anchors(xlsx_path):
    """Return {(excel_row, col_letter): media_filename} for every floating image."""
    with zipfile.ZipFile(xlsx_path) as z:
        drawing_xml = z.read("xl/drawings/drawing1.xml")
        rels_xml = z.read("xl/drawings/_rels/drawing1.xml.rels")

    rels_ns = "http://schemas.openxmlformats.org/package/2006/relationships"
    rid_to_target = {
        rel.attrib["Id"]: rel.attrib["Target"]
        for rel in ET.fromstring(rels_xml)
    }

    xdr_ns = "http://schemas.openxmlformats.org/drawingml/2006/spreadsheetDrawing"
    a_ns = "http://schemas.openxmlformats.org/drawingml/2006/main"
    r_ns = "http://schemas.openxmlformats.org/officeDocument/2006/relationships"

    anchors = {}
    root = ET.fromstring(drawing_xml)
    for anchor in root:
        frm = anchor.find(f"{{{xdr_ns}}}from")
        if frm is None:
            continue
        col0 = int(frm.find(f"{{{xdr_ns}}}col").text)
        row0 = int(frm.find(f"{{{xdr_ns}}}row").text)
        blip = anchor.find(f".//{{{a_ns}}}blip")
        if blip is None:
            continue
        rid = blip.attrib[f"{{{r_ns}}}embed"]
        target = rid_to_target.get(rid)
        if not target:
            continue
        media_name = target.split("/")[-1]
        anchors[(row0 + 1, col_letter(col0))] = media_name
    return anchors


def extract_media(xlsx_path, media_name, dest_path):
    with zipfile.ZipFile(xlsx_path) as z:
        data = z.read(f"xl/media/{media_name}")
    dest_path.parent.mkdir(parents=True, exist_ok=True)
    dest_path.write_bytes(data)


def main():
    if len(sys.argv) != 2:
        print(f"usage: {sys.argv[0]} path/to/glossary.xlsx", file=sys.stderr)
        sys.exit(1)

    xlsx_path = Path(sys.argv[1])
    wb = openpyxl.load_workbook(xlsx_path, data_only=True)
    ws = wb.active

    anchors = parse_drawing_anchors(xlsx_path)

    cards_by_grade = defaultdict(list)
    qa_lines = ["# Word Wall data extraction QA report\n"]
    skipped = []

    for row in range(3, ws.max_row + 1):
        a_raw = ws[f"A{row}"].value
        if not a_raw or not str(a_raw).strip():
            continue
        d_raw = ws[f"D{row}"].value
        word = clean_word(a_raw, d_raw, row)

        for grade, (cur_col, img_col, fb_col, new_col) in GRADE_COLS.items():
            cols = {"current": cur_col, "image": img_col, "feedback": fb_col, "new_entry": new_col}

            cur_text = ws[f"{cur_col}{row}"].value
            new_text = ws[f"{new_col}{row}"].value
            text_source = "new_entry" if (new_text and str(new_text).strip()) else (
                "current" if (cur_text and str(cur_text).strip()) else None
            )
            raw_text = new_text if text_source == "new_entry" else cur_text
            text = clean_definition(raw_text, word) if text_source else ""

            image_source = None
            media_name = None
            for role in IMAGE_ROLE_PRIORITY:
                key = (row, cols[role])
                if key in anchors:
                    image_source = role
                    media_name = anchors[key]
                    break

            if not text and not media_name:
                continue  # word not used in this grade

            image_rel_path = None
            if media_name:
                ext = Path(media_name).suffix
                image_rel_path = f"{grade}/{row}_{slugify(word)}{ext}"
                extract_media(xlsx_path, media_name, IMAGES_DIR / image_rel_path)

            card = {
                "row": row,
                "word": word,
                "text": text,
                "image": image_rel_path,
            }
            cards_by_grade[grade].append(card)

            qa_lines.append(
                f"- row {row} | grade {grade} | word='{word}' | "
                f"text_source={text_source or 'none'} | image_source={image_source or 'none'}"
                + (f" ({media_name})" if media_name else "")
            )

    DATA_DIR.mkdir(parents=True, exist_ok=True)
    out = {g: cards_by_grade.get(g, []) for g in GRADE_COLS}
    (DATA_DIR / "vocab.json").write_text(json.dumps(out, indent=2))

    qa_lines.insert(1, f"\nTotal cards per grade: { {g: len(v) for g, v in out.items()} }\n")
    (DATA_DIR / "qa_report.md").write_text("\n".join(qa_lines) + "\n")

    for g in GRADE_COLS:
        print(f"grade {g}: {len(out[g])} cards")


if __name__ == "__main__":
    main()
